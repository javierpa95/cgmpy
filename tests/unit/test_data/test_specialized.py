# --------------------------------------------------------------------- helpers
def _write_dexcom_csv(path: Path) -> Path:
    """Write a tiny Dexcom-format CSV (Clarity export) at `path`."""
    df = pd.DataFrame(
        {
            "Marca temporal (AAAA-MM-DDThh:mm:ss)": pd.date_range(
                "2024-01-01", periods=12, freq="5min"
            ).strftime("%Y-%m-%dT%H:%M:%S"),
            "Nivel de glucosa (mg/dL)": [110] * 12,
        }
    )
    df.to_csv(path, index=False)
    return path


def _write_libreview_csv(path: Path) -> Path:
    """Write a tiny Libreview-format CSV with the typical two-row header."""
    n = 12
    times = pd.date_range("2024-01-01", periods=n, freq="15min").strftime(
        "%d-%m-%Y %H:%M"
    )
    # Libreview has 2 banner rows above the actual header
    with open(path, "w", encoding="utf-8", newline="") as fh:
        fh.write("Patient export\n")
        fh.write("Generated by Libreview\n")
        fh.write(
            "Dispositivo,Numero de serie,"
            "Sello de tiempo del dispositivo,"
            "Tipo de registro,"
            "Historial de glucosa mg/dL\n"
        )
        for t in times:
            fh.write(f"FreeStyle Libre 3,XXX,{t},0,110\n")
    return path


