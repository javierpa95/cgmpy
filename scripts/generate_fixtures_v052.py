"""Deterministic generator for the v0.5.2 synthetic test fixtures.

This script writes hand-validated, byte-for-byte reproducible CSV fixtures
under tests/fixtures/. It is intentionally NOT a test itself; it is a
maintenance script that documents the construction of the fixtures.

Re-run only when the device format (column names, timestamp format)
changes in cgmpy/data/specialized.py.

Usage:
    python scripts/generate_fixtures_v052.py
"""

from __future__ import annotations

import math
from pathlib import Path

import pandas as pd


# ---------------------------------------------------------------------------
# Configuration
# ---------------------------------------------------------------------------
N_ROWS_24H = 288  # 24h at 5-min intervals
N_ROWS_1H = 12  # 1h at 5-min intervals
START = pd.Timestamp("2024-01-01 00:00:00")
GLUCOSE_CONSTANT = 120  # mg/dL

# Device-specific column names (must match cgmpy/data/specialized.py)
DEXCOM_DATE = "Marca temporal (AAAA-MM-DDThh:mm:ss)"
DEXCOM_GLUCOSE = "Nivel de glucosa (mg/dL)"

LIBREVIEW_DATE = "Sello de tiempo del dispositivo"
LIBREVIEW_GLUCOSE = "Historial de glucosa mg/dL"

MEDTRONIC_DATE = "Fecha y hora"
MEDTRONIC_GLUCOSE = "Valor del sensor (mg/dL)"

TANDEM_DATE = "Timestamp"
TANDEM_GLUCOSE = "CGM Glucose Value (mg/dL)"


def _out(base: Path, *parts: str) -> Path:
    return base.joinpath(*parts)


# ---------------------------------------------------------------------------
# Device fixtures (constant 120 mg/dL, 24h at 5-min intervals, 288 rows)
# ---------------------------------------------------------------------------
def _build_timestamps_24h() -> list[pd.Timestamp]:
    """Return 288 evenly spaced 5-min timestamps starting at 2024-01-01 00:00:00."""
    return list(pd.date_range(start=START, periods=N_ROWS_24H, freq="5min"))


def write_dexcom_constant_120(base: Path) -> Path:
    path = _out(base, "devices", "dexcom_constant_120.csv")
    timestamps = _build_timestamps_24h()
    df = pd.DataFrame(
        {
            DEXCOM_DATE: [t.strftime("%Y-%m-%dT%H:%M:%S") for t in timestamps],
            DEXCOM_GLUCOSE: [GLUCOSE_CONSTANT] * N_ROWS_24H,
        }
    )
    df.to_csv(path, index=False, lineterminator="\n")
    return path


def write_libreview_constant_120(base: Path) -> Path:
    """Libreview has 2 banner rows above the actual header (header=2)."""
    path = _out(base, "devices", "libreview_constant_120.csv")
    timestamps = _build_timestamps_24h()
    with path.open("w", encoding="utf-8", newline="") as fh:
        # Two banner rows (skipped by header=2)
        fh.write("Patient export\n")
        fh.write("Generated by Libreview\n")
        # Real header on row index 2 (0-based)
        fh.write(
            f"Dispositivo,Numero de serie,{LIBREVIEW_DATE},Tipo de registro,{LIBREVIEW_GLUCOSE}\n"
        )
        for t in timestamps:
            # Libreview uses DD-MM-YYYY HH:MM (no seconds)
            fh.write(f"FreeStyle Libre 3,XXX,{t.strftime('%d-%m-%Y %H:%M')},0,{GLUCOSE_CONSTANT}\n")
    return path


