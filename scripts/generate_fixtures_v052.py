# ---------------------------------------------------------------------------
# Synthetic (non-device-bound) fixtures
# ---------------------------------------------------------------------------
def write_sine_24h(base: Path) -> Path:
    """g(t) = 120 + 30 * sin(2*pi*t/720), t in minutes, 5-min samples, 24h.

    The chosen 24h window (288 samples) contains exactly 2 full periods
    (288 / (720/5) = 288/144 = 2), so:
      - mean(g) = 120 exactly
      - sample SD (ddof=1) = 30 * sqrt((287/288) * 1/2) = 30*sqrt(287/576)
        = 30 * sqrt(0.4982638888...) = 30 * 0.705878... = 21.1766...
      - min = 90, max = 150
      - TIR 70-180 = 100% (everything inside [90, 150])
      - GMI = round(3.31 + 0.02392*120, 2) = 6.18
    """
    path = _out(base, "synthetic", "sine_24h.csv")
    timestamps = list(pd.date_range(start=START, periods=N_ROWS_24H, freq="5min"))
    minutes = [int((t - START).total_seconds() // 60) for t in timestamps]
    glucose = [120 + 30 * math.sin(2 * math.pi * m / 720) for m in minutes]
    df = pd.DataFrame({"time": timestamps, "glucose": glucose})
    df.to_csv(path, index=False, lineterminator="\n")
    return path


# ---------------------------------------------------------------------------
# Driver
# ---------------------------------------------------------------------------
def main() -> None:
    base = Path("tests/fixtures")
    writers = [
        # Device fixtures
        ("dexcom_constant_120.csv", write_dexcom_constant_120),
        ("libreview_constant_120.csv", write_libreview_constant_120),
        ("medtronic_constant_120.csv", write_medtronic_constant_120),
        ("tandem_constant_120.csv", write_tandem_constant_120),
        # Edge cases
        ("edge_cases/empty.csv", write_edge_empty),
        ("edge_cases/single_row.csv", write_edge_single_row),
        ("edge_cases/all_nan_glucose.csv", write_edge_all_nan),
        ("edge_cases/with_gap.csv", write_edge_with_gap),
        ("edge_cases/out_of_range_high.csv", write_edge_out_of_range_high),
        ("edge_cases/out_of_range_low.csv", write_edge_out_of_range_low),
        # Synthetic
        ("sine_24h.csv", write_sine_24h),
    ]
    for _rel, fn in writers:
        out = fn(base)
        size = out.stat().st_size
        print(f"  {out}  ({size} bytes)")


if __name__ == "__main__":
    main()
